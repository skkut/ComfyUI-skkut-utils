"""
Skutils Style Selector — feature subpackage of ComfyUI-skkut-utils.

A style-selection node that combines a main positive prompt with a bundled
library of 1,416 categorized styles (curated Clio Style Library + OreX sets,
a curated Classified set, plus one hand-added style) and
emits the positive prompt, a merged negative prompt, and a filename-friendly
style name.  Styles can be combined into one prompt or emitted one per
style for batch execution.

A read-only bundled ``styles.json`` is merged at read time with a **user
layer** (``user_styles.json`` under ComfyUI's user directory): new styles,
field-level overrides of bundled styles, and the layout/order saved by the
picker and the organizer tool.  User changes therefore survive plugin
updates; nothing ever writes ``styles.json``.

Implementation notes:
  * skutils_style_selector.py — the node.
  * library.py — bundled cache, user-layer parse/merge/CRUD, thumbnails.
  * routes.py — the picker's library/thumbnail/custom-style HTTP endpoints.
  * styles.json + assets/thumbs/ — the bundled library (generated by
    scripts/build_style_library.py).
  * web/skutils_style_selector.js — the visual picker.
"""

