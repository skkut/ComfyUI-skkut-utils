# Thumbnail resolution
# ---------------------------------------------------------------------------

def bundled_thumb_path(name):
    """Filesystem path of a bundled entry's thumbnail, or ``None``.

    The entry is found by name first, so the request never supplies a path;
    the resolved file is then containment-checked anyway.

    This intentionally avoids building the full merged library: the picker
    requests one thumbnail per bundled style, and merging 1,400+ entries for
    each request would be wasteful.  A name shadowed by a user style is not a
    bundled style, so it has no bundled thumbnail (the user style supplies its
    own URL, if any).
    """
    folded = name.casefold()
    if any(style["name"].casefold() == folded for style in user_library()["styles"]):
        return None

    exact, by_folded = _lookup(bundled_library()["styles"])
    entry = exact.get(name) or by_folded.get(folded)
    if not entry:
        return None
    thumb_name = entry.get("thumb")
    if not isinstance(thumb_name, str) or not thumb_name:
        return None

    root = os.path.realpath(THUMBS_DIR)
    candidate = os.path.realpath(os.path.join(root, thumb_name))
    try:
        if os.path.commonpath([root, candidate]) != root:
            return None
    except ValueError:
        return None
    return candidate if os.path.isfile(candidate) else None


def filename_slug(name):
    """A style name flattened for use in a filename."""
    slug = re.sub(r"[^A-Za-z0-9]+", "_", str(name)).strip("_")
    return slug
