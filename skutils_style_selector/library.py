"""Style library for the Skutils Style Selector.

Two layers, merged at read time:

  * **Bundled** — ``styles.json`` + ``assets/thumbs/*.webp`` beside this
    module, generated by ``scripts/build_style_library.py``.  Read-only.
  * **Custom** — ``custom_styles.json`` under ComfyUI's user directory,
    edited from the picker's in-panel editor.  Survives updates.

Everything here is import-safe outside ComfyUI: ``folder_paths`` is only
touched when the custom library is read or written, and a missing or
corrupt custom file is treated as an empty one.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import re
import threading

LOGGER = logging.getLogger("skutils-utils.skutils_style_selector")

PACKAGE_DIR = os.path.dirname(os.path.abspath(__file__))
BUNDLED_PATH = os.path.join(PACKAGE_DIR, "styles.json")
THUMBS_DIR = os.path.join(PACKAGE_DIR, "assets", "thumbs")

CUSTOM_DIR_NAME = "skkut_style_selector"
CUSTOM_FILE_NAME = "custom_styles.json"
CUSTOM_SECTION = "Custom"

MAX_NAME_LEN = 120
MAX_TEXT_LEN = 20000
MAX_SECTION_LEN = 60

_URL_SCHEMES = ("http://", "https://")

_CUSTOM_FIELDS = ("name", "section", "prompt", "negative", "template", "thumbnail")

_library_lock = threading.Lock()
_bundled_cache = None
_thumb_version_cache = None
_thumb_version_lock = threading.Lock()


# ---------------------------------------------------------------------------
# Bundled library
# ---------------------------------------------------------------------------

def bundled_library():
    """The generated library as ``{"version", "credits", "sections", "styles"}``.

    Loaded once.  A missing or broken file yields an empty library rather
    than an exception — the node still works, it just offers no styles.
    """
    global _bundled_cache
    if _bundled_cache is not None:
        return _bundled_cache

    data = {"version": 1, "credits": {}, "sections": [], "styles": []}
    try:
        with open(BUNDLED_PATH, "r", encoding="utf-8") as handle:
            loaded = json.load(handle)
        if isinstance(loaded, dict):
            styles = loaded.get("styles")
            if isinstance(styles, list):
                data["styles"] = [entry for entry in styles if _is_entry(entry)]
            sections = loaded.get("sections")
            if isinstance(sections, list):
                data["sections"] = [str(s) for s in sections if isinstance(s, str)]
            if isinstance(loaded.get("credits"), dict):
                data["credits"] = loaded["credits"]
            if isinstance(loaded.get("version"), int):
                data["version"] = loaded["version"]
    except FileNotFoundError:
        LOGGER.warning("Bundled style library not found: %s", BUNDLED_PATH)
    except (OSError, ValueError) as error:
        LOGGER.warning("Could not read bundled style library %s: %s", BUNDLED_PATH, error)

    for entry in data["styles"]:
        entry.setdefault("source", "bundled")
        entry.setdefault("negative", "")
        entry.setdefault("template", None)
        entry.setdefault("thumb", None)

    _bundled_cache = data
    return data


def _is_entry(entry):
    return (
        isinstance(entry, dict)
        and isinstance(entry.get("name"), str)
        and bool(entry["name"].strip())
        and isinstance(entry.get("prompt"), str)
    )


# ---------------------------------------------------------------------------
# Custom library
# ---------------------------------------------------------------------------

def custom_library_path():
    """Path of ``custom_styles.json``, or ``None`` if there is no user dir."""
    user_dir = _user_directory()
    if not user_dir:
        return None
    return os.path.join(user_dir, "default", CUSTOM_DIR_NAME, CUSTOM_FILE_NAME)


def _user_directory():
    """ComfyUI's user directory, tolerating older ``folder_paths`` builds."""
    try:
        import folder_paths
    except Exception:
        return None

    getter = getattr(folder_paths, "get_user_directory", None)
    if callable(getter):
        try:
            directory = getter()
            if directory:
                return directory
        except Exception:
            pass

    base = getattr(folder_paths, "base_path", None)
    if base:
        return os.path.join(base, "user")
    return None


def custom_library():
    """The custom styles as a list of normalized entries (possibly empty)."""
    path = custom_library_path()
    if not path or not os.path.exists(path):
        return []
    try:
        with open(path, "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError) as error:
        LOGGER.warning("Could not read custom styles %s: %s", path, error)
        return []

    raw_styles = data.get("styles") if isinstance(data, dict) else data
    if not isinstance(raw_styles, list):
        return []

    entries = []
    for raw in raw_styles:
        try:
            entry = _normalize_custom(raw)
        except (TypeError, ValueError):
            continue
        entry["source"] = "custom"
        entry["thumb"] = None
        entries.append(entry)
    return entries


def thumb_version():
    """A short fingerprint of the bundled thumbnails, for cache busting.

    The picker appends this to every thumbnail URL.  Browsers cache the
    images for a day, so without it a replaced thumbnail keeps showing the
    old image even after ComfyUI is restarted.  File names, sizes and mtimes
    all feed the digest, so replacing a thumbnail (or the set of them) yields
    a new URL.

    Computed once per process — replacing the files while ComfyUI is running
    takes effect after the restart that also reloads ``styles.json``.
    """
    global _thumb_version_cache
    if _thumb_version_cache is not None:
        return _thumb_version_cache

    with _thumb_version_lock:
        if _thumb_version_cache is not None:
            return _thumb_version_cache
        digest = hashlib.sha1()
        for entry in bundled_library()["styles"]:
            thumb = entry.get("thumb")
            if not isinstance(thumb, str) or not thumb:
                continue
            try:
                stat = os.stat(os.path.join(THUMBS_DIR, thumb))
            except OSError:
                continue
            digest.update(thumb.encode("utf-8"))
            digest.update(b"\0")
            digest.update(str(stat.st_size).encode("ascii"))
            digest.update(b"\0")
            digest.update(str(stat.st_mtime_ns).encode("ascii"))
            digest.update(b"\0")
        _thumb_version_cache = digest.hexdigest()[:12]
        return _thumb_version_cache


def merged_library():
    """Bundled + custom styles, with custom entries appended."""
    bundled = bundled_library()
    custom = custom_library()
    styles = list(bundled["styles"]) + custom

    sections = list(bundled["sections"])
    for entry in custom:
        if entry["section"] not in sections:
            sections.append(entry["section"])
    if custom and CUSTOM_SECTION not in sections:
        sections.append(CUSTOM_SECTION)

    return {
        "version": bundled["version"],
        "thumb_version": thumb_version(),
        "credits": bundled["credits"],
        "sections": sections,
        "styles": styles,
    }


def _lookup(styles):
    """Name -> entry, case-insensitive; exact spelling wins on collisions."""
    lookup = {}
    for entry in styles:
        lookup.setdefault(entry["name"], entry)
    folded = {}
    for name, entry in lookup.items():
        folded.setdefault(name.casefold(), entry)
    return lookup, folded


def resolve(names):
    """Library entries for ``names``, preserving order; unknown names skipped."""
    styles = merged_library()["styles"]
    exact, folded = _lookup(styles)

    resolved = []
    seen = set()
    for name in names:
        entry = exact.get(name) or folded.get(name.casefold())
        if entry is None or entry["name"] in seen:
            continue
        seen.add(entry["name"])
        resolved.append(entry)
    return resolved


def get_entry(name):
    """One merged entry by name (case-insensitive), or ``None``."""
    exact, folded = _lookup(merged_library()["styles"])
    return exact.get(name) or folded.get(name.casefold())


# ---------------------------------------------------------------------------
# Custom style CRUD
# ---------------------------------------------------------------------------

def _normalize_custom(raw):
    if not isinstance(raw, dict):
        raise TypeError("style must be an object")
    name = raw.get("name")
    prompt = raw.get("prompt")
    if not isinstance(name, str) or not name.strip():
        raise ValueError("A style needs a name.")
    if not isinstance(prompt, str) or not prompt.strip():
        raise ValueError("A style needs a prompt.")

    section = raw.get("section")
    if not isinstance(section, str) or not section.strip():
        section = CUSTOM_SECTION
    template = raw.get("template")
    if not isinstance(template, str) or not template.strip():
        template = None
    negative = raw.get("negative")
    if not isinstance(negative, str):
        negative = ""
    thumbnail = raw.get("thumbnail")
    if not isinstance(thumbnail, str):
        thumbnail = ""

    return {
        "name": name.strip(),
        "section": section.strip(),
        "prompt": prompt,
        "negative": negative,
        "template": template,
        "thumbnail": thumbnail.strip(),
    }


def _validate(entry, original_name=None):
    name = entry["name"]
    if len(name) > MAX_NAME_LEN:
        raise ValueError(f"Style names are limited to {MAX_NAME_LEN} characters.")
    if len(entry["section"]) > MAX_SECTION_LEN:
        raise ValueError(f"Section names are limited to {MAX_SECTION_LEN} characters.")
    for field in ("prompt", "negative"):
        if len(entry[field]) > MAX_TEXT_LEN:
            raise ValueError(f"The {field} is too long (limit {MAX_TEXT_LEN} characters).")
    if entry["template"] and len(entry["template"]) > MAX_TEXT_LEN:
        raise ValueError(f"The template is too long (limit {MAX_TEXT_LEN} characters).")

    thumbnail = entry["thumbnail"]
    if thumbnail and not thumbnail.lower().startswith(_URL_SCHEMES):
        raise ValueError("The thumbnail must be an http:// or https:// URL.")

    # Only custom styles may be edited, and a rename must not shadow
    # anything else in the merged library.
    existing_custom = {item["name"] for item in custom_library()}
    if original_name is not None and original_name not in existing_custom:
        raise ValueError(f"'{original_name}' is not a custom style.")

    taken = {
        item["name"].casefold()
        for item in merged_library()["styles"]
        if original_name is None or item["name"] != original_name
    }
    if name.casefold() in taken:
        raise ValueError(f"A style named '{name}' already exists.")


def save_custom(style, original_name=None):
    """Create (``original_name=None``) or replace/rename a custom style."""
    entry = _normalize_custom(style)
    with _library_lock:
        _validate(entry, original_name)

        styles = custom_library()
        if original_name is not None:
            styles = [item for item in styles if item["name"] != original_name]
        styles = [item for item in styles if item["name"] != entry["name"]]
        styles.append(entry)

        _write_custom(styles)
    return entry


def delete_custom(name):
    """Delete a custom style; returns True when one was removed."""
    with _library_lock:
        styles = custom_library()
        remaining = [item for item in styles if item["name"] != name]
        if len(remaining) == len(styles):
            return False
        _write_custom(remaining)
    return True


def _write_custom(styles):
    path = custom_library_path()
    if not path:
        raise RuntimeError("ComfyUI's user directory is unavailable.")

    os.makedirs(os.path.dirname(path), exist_ok=True)
    temp_path = path + ".tmp"
    payload = {
        "version": 1,
        "styles": [
            {field: entry.get(field) for field in _CUSTOM_FIELDS}
            for entry in styles
        ],
    }
    with open(temp_path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=1)
        handle.write("\n")
    os.replace(temp_path, path)


# ---------------------------------------------------------------------------
# Thumbnail resolution
# ---------------------------------------------------------------------------

def bundled_thumb_path(name):
    """Filesystem path of a bundled entry's thumbnail, or ``None``.

    The entry is found by name first, so the request never supplies a path;
    the resolved file is then containment-checked anyway.
    """
    entry = get_entry(name)
    if not entry or entry.get("source") == "custom":
        return None
    thumb_name = entry.get("thumb")
    if not isinstance(thumb_name, str) or not thumb_name:
        return None

    root = os.path.realpath(THUMBS_DIR)
    candidate = os.path.realpath(os.path.join(root, thumb_name))
    try:
        if os.path.commonpath([root, candidate]) != root:
            return None
    except ValueError:
        return None
    return candidate if os.path.isfile(candidate) else None


def filename_slug(name):
    """A style name flattened for use in a filename."""
    slug = re.sub(r"[^A-Za-z0-9]+", "_", str(name)).strip("_")
    return slug
