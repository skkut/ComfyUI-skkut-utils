"""Style library for the Skutils Style Selector.

Three layers, merged at read time:

  * **Bundled** — ``styles.json`` + ``assets/thumbs/*.webp`` beside this
    module, generated by ``scripts/build_style_library.py``.  Read-only:
    plugin updates replace it, so no user change is ever stored there.
  * **User** — ``user_styles.json`` under ComfyUI's user directory.  Holds
    new styles, per-style overrides of bundled styles, and the layout
    (section order, style order, pins).  A plugin update replaces the
    bundled layer only; the user layer keeps overriding it.
  * **Legacy custom** — ``custom_styles.json`` in the same directory.  Read
    as a fallback when ``user_styles.json`` does not exist yet; new writes
    always go to ``user_styles.json``.

Everything here is import-safe outside ComfyUI: ``folder_paths`` is only
touched when the user file is read or written through the normal entry
points, and a missing user file is treated as empty.  The ``parse_*``,
``merge_library`` and ``write_user_library`` helpers are pure/public and are
also used by ``tools/reorganize_styles.py``.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import re
import tempfile
import threading

LOGGER = logging.getLogger("skutils-utils.skutils_style_selector")

PACKAGE_DIR = os.path.dirname(os.path.abspath(__file__))
BUNDLED_PATH = os.path.join(PACKAGE_DIR, "styles.json")
THUMBS_DIR = os.path.join(PACKAGE_DIR, "assets", "thumbs")

USER_DIR_NAME = "skkut_style_selector"
USER_FILE_NAME = "user_styles.json"
LEGACY_CUSTOM_FILE_NAME = "custom_styles.json"
CUSTOM_SECTION = "Custom"
USER_FILE_VERSION = 1

MAX_NAME_LEN = 120
MAX_TEXT_LEN = 20000
MAX_SECTION_LEN = 60

_URL_SCHEMES = ("http://", "https://")

USER_STYLE_FIELDS = ("name", "section", "prompt", "negative", "template", "thumbnail")
OVERRIDE_FIELDS = ("section", "prompt", "negative", "template", "thumbnail")

_library_lock = threading.Lock()
_bundled_cache = None
_thumb_version_cache = None
_thumb_version_lock = threading.Lock()


class UserLibraryError(RuntimeError):
    """The user styles file exists but cannot be read or parsed."""


# ---------------------------------------------------------------------------
# Bundled library
# ---------------------------------------------------------------------------

def parse_bundled(raw):
    """Normalize a bundled library payload (``styles.json`` as a dict)."""
    data = {"version": 1, "credits": {}, "sections": [], "styles": []}
    if isinstance(raw, dict):
        styles = raw.get("styles")
        if isinstance(styles, list):
            data["styles"] = [dict(entry) for entry in styles if _is_entry(entry)]
        sections = raw.get("sections")
        if isinstance(sections, list):
            data["sections"] = [str(s) for s in sections if isinstance(s, str)]
        if isinstance(raw.get("credits"), dict):
            data["credits"] = raw["credits"]
        if isinstance(raw.get("version"), int):
            data["version"] = raw["version"]

    for entry in data["styles"]:
        entry.setdefault("source", "bundled")
        entry.setdefault("negative", "")
        entry.setdefault("template", None)
        entry.setdefault("thumb", None)
    return data


def bundled_library():
    """The bundled library as ``{"version", "credits", "sections", "styles"}``.

    Loaded once.  A missing or broken file yields an empty library rather
    than an exception — the node still works, it just offers no styles.
    """
    global _bundled_cache
    if _bundled_cache is not None:
        return _bundled_cache

    raw = None
    try:
        with open(BUNDLED_PATH, "r", encoding="utf-8") as handle:
            raw = json.load(handle)
    except FileNotFoundError:
        LOGGER.warning("Bundled style library not found: %s", BUNDLED_PATH)
    except (OSError, ValueError) as error:
        LOGGER.warning("Could not read bundled style library %s: %s", BUNDLED_PATH, error)

    _bundled_cache = parse_bundled(raw)
    return _bundled_cache


def _is_entry(entry):
    return (
        isinstance(entry, dict)
        and isinstance(entry.get("name"), str)
        and bool(entry["name"].strip())
        and isinstance(entry.get("prompt"), str)
    )


# ---------------------------------------------------------------------------
# User library: paths
# ---------------------------------------------------------------------------

def user_library_path():
    """Path of ``user_styles.json``, or ``None`` if there is no user dir."""
    user_dir = _user_directory()
    if not user_dir:
        return None
    return os.path.join(user_dir, "default", USER_DIR_NAME, USER_FILE_NAME)


def legacy_custom_library_path():
    """Path of the pre-``user_styles.json`` custom file, or ``None``."""
    user_dir = _user_directory()
    if not user_dir:
        return None
    return os.path.join(user_dir, "default", USER_DIR_NAME, LEGACY_CUSTOM_FILE_NAME)


def _user_directory():
    """ComfyUI's user directory, tolerating older ``folder_paths`` builds."""
    try:
        import folder_paths
    except Exception:
        return None

    getter = getattr(folder_paths, "get_user_directory", None)
    if callable(getter):
        try:
            directory = getter()
            if directory:
                return directory
        except Exception:
            pass

    base = getattr(folder_paths, "base_path", None)
    if base:
        return os.path.join(base, "user")
    return None


# ---------------------------------------------------------------------------
# User library: model
# ---------------------------------------------------------------------------

def empty_user_library():
    """An empty user library in the normalized shape."""
    return {
        "version": USER_FILE_VERSION,
        "styles": [],
        "overrides": {},
        "layout": {"sections": [], "order": []},
    }


def parse_user_library(raw):
    """Normalize a ``user_styles.json`` payload (or a legacy custom file).

    Invalid style entries and override fields are dropped, so a hand-edited
    file degrades gracefully instead of breaking the picker.
    """
    data = empty_user_library()
    if not isinstance(raw, dict):
        return data

    raw_styles = raw.get("styles")
    if isinstance(raw_styles, list):
        seen = set()
        for item in raw_styles:
            try:
                entry = _normalize_custom(item)
            except (TypeError, ValueError):
                continue
            key = entry["name"].casefold()
            if key in seen:
                continue
            seen.add(key)
            data["styles"].append(entry)

    raw_overrides = raw.get("overrides")
    if isinstance(raw_overrides, dict):
        for name, fields in raw_overrides.items():
            if not isinstance(name, str) or not name.strip() or not isinstance(fields, dict):
                continue
            clean = {}
            if isinstance(fields.get("section"), str) and fields["section"].strip():
                clean["section"] = fields["section"].strip()
            if isinstance(fields.get("prompt"), str):
                clean["prompt"] = fields["prompt"]
            if isinstance(fields.get("negative"), str):
                clean["negative"] = fields["negative"]
            if "template" in fields:
                template = fields["template"]
                clean["template"] = (
                    template if isinstance(template, str) and template.strip() else None
                )
            if isinstance(fields.get("thumbnail"), str):
                clean["thumbnail"] = fields["thumbnail"].strip()
            if clean:
                data["overrides"][name.strip()] = clean

    layout = raw.get("layout")
    if isinstance(layout, dict):
        sections = []
        seen_sections = set()
        raw_sections = layout.get("sections")
        if isinstance(raw_sections, list):
            for item in raw_sections:
                if not isinstance(item, str):
                    continue
                section = item.strip()
                if not section or section in seen_sections:
                    continue
                seen_sections.add(section)
                sections.append(section)

        order = []
        seen_names = set()
        raw_order = layout.get("order")
        if isinstance(raw_order, list):
            for item in raw_order:
                if isinstance(item, str):
                    item = {"name": item}
                if not isinstance(item, dict):
                    continue
                name = item.get("name")
                if not isinstance(name, str) or not name.strip():
                    continue
                name = name.strip()
                if name in seen_names:
                    continue
                seen_names.add(name)
                entry = {"name": name}
                if item.get("pinned") is True:
                    entry["pinned"] = True
                order.append(entry)

        data["layout"] = {"sections": sections, "order": order}
    return data


def load_user_library(path):
    """Read a user file by path.

    Returns ``None`` when the file does not exist and raises
    :class:`UserLibraryError` when it exists but cannot be parsed — that
    distinction lets writers refuse to overwrite a corrupt file.
    """
    if not path or not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as handle:
            raw = json.load(handle)
    except (OSError, ValueError) as error:
        raise UserLibraryError(f"Could not read user styles {path}: {error}") from error
    return parse_user_library(raw)


def user_library():
    """The user library, falling back to the legacy custom file.

    A missing file yields an empty library; a corrupt one is logged and
    treated as empty for read-only use (writes use the strict loader).
    """
    path = user_library_path()
    data = None
    if path and os.path.exists(path):
        try:
            data = load_user_library(path)
        except UserLibraryError as error:
            LOGGER.warning("%s", error)
    if data is None:
        legacy = legacy_custom_library_path()
        if legacy and os.path.exists(legacy):
            try:
                data = load_user_library(legacy)
            except UserLibraryError as error:
                LOGGER.warning("%s", error)
    return data if data is not None else empty_user_library()


def _load_user_data_strict():
    """The user library for writers: raises instead of silently emptying."""
    path = user_library_path()
    if not path:
        raise RuntimeError("ComfyUI's user directory is unavailable.")
    data = load_user_library(path)
    if data is None:
        legacy = legacy_custom_library_path()
        if legacy and os.path.exists(legacy):
            data = load_user_library(legacy)
    return data if data is not None else empty_user_library()


# ---------------------------------------------------------------------------
# Merging
# ---------------------------------------------------------------------------

def merge_library(bundled, user):
    """Merge a bundled and a user library into the picker's payload.

    * A user style with the same name (case-insensitive) as a bundled style
      replaces it, so a plugin update can never duplicate or shadow it.
    * ``overrides`` overlay their fields onto the matching bundled entry
      (matched by the bundled name), preserving the plugin's other fields.
    * ``layout.order`` fixes the order of the names it lists (listed styles
      first, in that order); names added by a later plugin update stay
      after the listed ones, in their bundled order.
    * ``layout.sections`` sets the section order; new sections from the
      plugin are appended, so nothing ever disappears.
    """
    user_styles = user.get("styles") or []
    overrides = user.get("overrides") or {}
    user_names = {entry["name"].casefold() for entry in user_styles}

    styles = []
    for entry in bundled.get("styles") or []:
        if entry["name"].casefold() in user_names:
            continue  # a user style with this name replaces the bundled one
        merged = dict(entry)
        override = overrides.get(entry["name"])
        if isinstance(override, dict):
            for field in OVERRIDE_FIELDS:
                if field in override:
                    merged[field] = override[field]
            merged["overridden"] = True
        styles.append(merged)

    for entry in user_styles:
        merged = dict(entry)
        merged["source"] = "custom"
        merged["thumb"] = None
        merged["negative"] = merged.get("negative") or ""
        merged["template"] = merged.get("template") or None
        styles.append(merged)

    layout = user.get("layout") or {}
    order = layout.get("order") or []
    rank = {}
    pins = {}
    for index, item in enumerate(order):
        name = item.get("name")
        if not isinstance(name, str):
            continue
        rank.setdefault(name, index)
        pins[name] = item.get("pinned") is True

    for entry in styles:
        name = entry.get("name")
        if name in pins:
            entry["pinned"] = pins[name]
        else:
            entry["pinned"] = entry.get("pinned") is True

    styles.sort(key=lambda entry: rank.get(entry.get("name"), len(rank)))

    sections = []

    def add_section(section):
        if isinstance(section, str) and section and section not in sections:
            sections.append(section)

    for section in layout.get("sections") or []:
        add_section(section)
    for section in bundled.get("sections") or []:
        add_section(section)
    for entry in styles:
        add_section(entry.get("section"))

    return {
        "version": bundled.get("version", 1),
        "credits": bundled.get("credits", {}),
        "sections": sections,
        "styles": styles,
    }


def merged_library():
    """Bundled + user styles, merged, plus the thumbnail fingerprint."""
    data = merge_library(bundled_library(), user_library())
    data["thumb_version"] = thumb_version()
    return data


def _lookup(styles):
    """Name -> entry, case-insensitive; exact spelling wins on collisions."""
    lookup = {}
    for entry in styles:
        lookup.setdefault(entry["name"], entry)
    folded = {}
    for name, entry in lookup.items():
        folded.setdefault(name.casefold(), entry)
    return lookup, folded


def resolve(names):
    """Library entries for ``names``, preserving order; unknown names skipped."""
    styles = merged_library()["styles"]
    exact, folded = _lookup(styles)

    resolved = []
    seen = set()
    for name in names:
        entry = exact.get(name) or folded.get(name.casefold())
        if entry is None or entry["name"] in seen:
            continue
        seen.add(entry["name"])
        resolved.append(entry)
    return resolved


# ---------------------------------------------------------------------------
# Thumbnail fingerprint
# ---------------------------------------------------------------------------

def thumb_version():
    """A short fingerprint of the bundled thumbnails, for cache busting.

    The picker appends this to every bundled thumbnail URL.  Browsers cache
    the images for a day, so without it a replaced thumbnail keeps showing
    the old image even after ComfyUI is restarted.  File names, sizes and
    mtimes all feed the digest, so replacing a thumbnail (or the set of
    them) yields a new URL.

    Computed once per process — replacing the files while ComfyUI is running
    takes effect after the restart that also reloads ``styles.json``.
    """
    global _thumb_version_cache
    if _thumb_version_cache is not None:
        return _thumb_version_cache

    with _thumb_version_lock:
        if _thumb_version_cache is not None:
            return _thumb_version_cache
        digest = hashlib.sha1()
        for entry in bundled_library()["styles"]:
            thumb = entry.get("thumb")
            if not isinstance(thumb, str) or not thumb:
                continue
            try:
                stat = os.stat(os.path.join(THUMBS_DIR, thumb))
            except OSError:
                continue
            digest.update(thumb.encode("utf-8"))
            digest.update(b"\0")
            digest.update(str(stat.st_size).encode("ascii"))
            digest.update(b"\0")
            digest.update(str(stat.st_mtime_ns).encode("ascii"))
            digest.update(b"\0")
        _thumb_version_cache = digest.hexdigest()[:12]
        return _thumb_version_cache


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------

def _normalize_custom(raw):
    if not isinstance(raw, dict):
        raise TypeError("style must be an object")
    name = raw.get("name")
    prompt = raw.get("prompt")
    if not isinstance(name, str) or not name.strip():
        raise ValueError("A style needs a name.")
    if not isinstance(prompt, str) or not prompt.strip():
        raise ValueError("A style needs a prompt.")

    section = raw.get("section")
    if not isinstance(section, str) or not section.strip():
        section = CUSTOM_SECTION
    template = raw.get("template")
    if not isinstance(template, str) or not template.strip():
        template = None
    negative = raw.get("negative")
    if not isinstance(negative, str):
        negative = ""
    thumbnail = raw.get("thumbnail")
    if not isinstance(thumbnail, str):
        thumbnail = ""

    return {
        "name": name.strip(),
        "section": section.strip(),
        "prompt": prompt,
        "negative": negative,
        "template": template,
        "thumbnail": thumbnail.strip(),
    }


def _validate_fields(entry):
    name = entry["name"]
    if len(name) > MAX_NAME_LEN:
        raise ValueError(f"Style names are limited to {MAX_NAME_LEN} characters.")
    if len(entry["section"]) > MAX_SECTION_LEN:
        raise ValueError(f"Section names are limited to {MAX_SECTION_LEN} characters.")
    for field in ("prompt", "negative"):
        if len(entry[field]) > MAX_TEXT_LEN:
            raise ValueError(f"The {field} is too long (limit {MAX_TEXT_LEN} characters).")
    if entry["template"] and len(entry["template"]) > MAX_TEXT_LEN:
        raise ValueError(f"The template is too long (limit {MAX_TEXT_LEN} characters).")

    thumbnail = entry["thumbnail"]
    if thumbnail and not thumbnail.lower().startswith(_URL_SCHEMES):
        raise ValueError("The thumbnail must be an http:// or https:// URL.")


def _validate_custom(entry, original_name, user_data):
    _validate_fields(entry)

    # Only user styles may be edited, and a rename must not shadow
    # anything else in the merged library.
    existing = {item["name"] for item in user_data.get("styles") or []}
    if original_name is not None and original_name not in existing:
        raise ValueError(f"'{original_name}' is not a user style.")

    taken = {
        item["name"].casefold()
        for item in merge_library(bundled_library(), user_data)["styles"]
        if original_name is None or item["name"] != original_name
    }
    if entry["name"].casefold() in taken:
        raise ValueError(f"A style named '{entry['name']}' already exists.")


def _bundled_entry(name):
    for item in bundled_library()["styles"]:
        if item["name"] == name:
            return item
    return None


# ---------------------------------------------------------------------------
# User style CRUD
# ---------------------------------------------------------------------------

def save_custom(style, original_name=None):
    """Create (``original_name=None``) or replace/rename a user style."""
    entry = _normalize_custom(style)
    with _library_lock:
        data = _load_user_data_strict()
        _validate_custom(entry, original_name, data)

        styles = data["styles"]
        if original_name is not None:
            styles = [item for item in styles if item["name"] != original_name]
        styles = [item for item in styles if item["name"] != entry["name"]]
        styles.append(entry)
        data["styles"] = styles

        if original_name is not None and original_name != entry["name"]:
            for item in data["layout"]["order"]:
                if item.get("name") == original_name:
                    item["name"] = entry["name"]

        _write_user(data)
    return entry


def delete_custom(name):
    """Delete a user style; returns True when one was removed."""
    with _library_lock:
        data = _load_user_data_strict()
        styles = data["styles"]
        remaining = [item for item in styles if item["name"] != name]
        if len(remaining) == len(styles):
            return False
        data["styles"] = remaining
        data["layout"]["order"] = [
            item for item in data["layout"]["order"] if item.get("name") != name
        ]
        _write_user(data)
    return True


def save_override(name, style):
    """Store a user override of a bundled style.

    Only fields that differ from the bundled entry are stored, so plugin
    updates to the fields the user did not change still flow through.
    Saving values identical to the bundled entry removes the override.
    """
    entry = _normalize_custom(style)
    with _library_lock:
        source = _bundled_entry(name)
        if source is None:
            raise ValueError(f"'{name}' is not a bundled style.")
        _validate_fields(entry)

        data = _load_user_data_strict()
        stored = {}
        if entry["section"] != source["section"]:
            stored["section"] = entry["section"]
        if entry["prompt"] != source["prompt"]:
            stored["prompt"] = entry["prompt"]
        if entry["negative"] != (source.get("negative") or ""):
            stored["negative"] = entry["negative"]
        if entry["template"] != (source.get("template") or None):
            stored["template"] = entry["template"]
        if entry["thumbnail"] != (source.get("thumbnail") or ""):
            stored["thumbnail"] = entry["thumbnail"]

        if stored:
            data["overrides"][name] = stored
        else:
            data["overrides"].pop(name, None)
        _write_user(data)
    return entry


def delete_override(name):
    """Remove a user override (revert to the bundled style)."""
    with _library_lock:
        data = _load_user_data_strict()
        if name not in data["overrides"]:
            return False
        data["overrides"].pop(name)
        _write_user(data)
    return True


def user_payload(data):
    """Serialize a normalized user library to its on-disk shape."""
    layout = data.get("layout") or {}
    return {
        "version": USER_FILE_VERSION,
        "styles": [
            {field: entry.get(field) for field in USER_STYLE_FIELDS}
            for entry in data.get("styles") or []
        ],
        "overrides": {
            name: {field: fields[field] for field in OVERRIDE_FIELDS if field in fields}
            for name, fields in (data.get("overrides") or {}).items()
        },
        "layout": {
            "sections": list(layout.get("sections") or []),
            "order": [dict(item) for item in layout.get("order") or []],
        },
    }


def write_user_library(path, data):
    """Atomically write a normalized user library to ``path``."""
    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, exist_ok=True)
    handle, temporary = tempfile.mkstemp(
        prefix=".user-styles-", suffix=".json", dir=directory
    )
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            json.dump(user_payload(data), stream, ensure_ascii=False, indent=1)
            stream.write("\n")
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def _write_user(data):
    path = user_library_path()
    if not path:
        raise RuntimeError("ComfyUI's user directory is unavailable.")
    write_user_library(path, data)


